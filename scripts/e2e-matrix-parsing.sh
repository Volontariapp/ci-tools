#!/bin/bash

# Exit on error
set -e

JSON_FILE="e2e-matrix.json"
OUTPUT_ENV=".env"

if [ ! -f "$JSON_FILE" ]; then
    echo "Error: $JSON_FILE not found. This script requires a matrix file to resolve tags."
    exit 1
fi

# List of allowed services: single source of truth shared with validate-matrix-main.sh
SERVICES_FILE="$(dirname "${BASH_SOURCE[0]}")/e2e-services.txt"
ALLOWED_SERVICES=()
while IFS= read -r line; do
    [ -n "$line" ] && ALLOWED_SERVICES+=("$line")
done < "$SERVICES_FILE"

# Detect current repository and branch from GitHub environment
CURRENT_SERVICE=""
if [ -n "$GITHUB_REPOSITORY" ]; then
    CURRENT_SERVICE=${GITHUB_REPOSITORY#*/}
fi

# Take the head branch name for PRs, otherwise use the ref name (which is usually the branch for pushes)
if [ -n "$GITHUB_HEAD_REF" ]; then
    CURRENT_BRANCH="$GITHUB_HEAD_REF"
else
    CURRENT_BRANCH=${GITHUB_REF_NAME:-"main"}
fi

# Clear or create the .env file
echo "# Generated by e2e-matrix-parsing.sh" > "$OUTPUT_ENV"

# Validate JSON keys using jq
SERVICES_IN_JSON=$(jq -r 'keys[]' "$JSON_FILE")
for SERVICE in $SERVICES_IN_JSON; do
    IS_ALLOWED=false
    for ALLOWED in "${ALLOWED_SERVICES[@]}"; do
        if [ "$SERVICE" == "$ALLOWED" ]; then
            IS_ALLOWED=true
            break
        fi
    done
    if [ "$IS_ALLOWED" = false ]; then
        echo "Error: unknown service '$SERVICE' in $JSON_FILE"
        exit 1
    fi
done

# Function to resolve branch to tag
resolve_tag() {
    local branch=$1
    if [ "$branch" == "main" ]; then
        echo "latest"
    else
        # Replace / with - as buildx/GHA tags usually do
        echo "${branch//\//-}"
    fi
}

# The current service must be absent. A missing service defaults to main (transition for
# callers that predate a newly added service).
for SERVICE in "${ALLOWED_SERVICES[@]}"; do
    BRANCH_IN_JSON=$(jq -r --arg svc "$SERVICE" '.[$svc] // empty' "$JSON_FILE")
    if [ "$SERVICE" == "$CURRENT_SERVICE" ]; then
        if [ -n "$BRANCH_IN_JSON" ]; then
            echo "Error: Cannot specify version for current service '$SERVICE' in $JSON_FILE. It is automatically determined by the current branch ($CURRENT_BRANCH)."
            exit 1
        fi
    elif [ -z "$BRANCH_IN_JSON" ]; then
        echo "::warning::Service '$SERVICE' is missing from $JSON_FILE, defaulting to main. Add \"$SERVICE\": \"main\" to silence this warning."
    fi
done

# Process each allowed service and generate output
for SERVICE in "${ALLOWED_SERVICES[@]}"; do
    # Try to get branch from JSON
    BRANCH=$(jq -r --arg svc "$SERVICE" '.[$svc] // empty' "$JSON_FILE")
    BRANCH=${BRANCH:-main}

    if [ "$SERVICE" == "$CURRENT_SERVICE" ]; then
        # Use current branch for the service being tested
        BRANCH=$CURRENT_BRANCH
    fi

    TAG=$(resolve_tag "$BRANCH")
    
    # Convert service name to env var format
    ENV_VAR_NAME=$(echo "$SERVICE" | tr '[:lower:]-' '[:upper:]_')_TAG
    
    # Write to .env file
    echo "${ENV_VAR_NAME}=${TAG}" >> "$OUTPUT_ENV"
    
    # Output for GitHub Actions
    if [ -n "$GITHUB_ENV" ]; then
        echo "${ENV_VAR_NAME}=${TAG}" >> "$GITHUB_ENV"
    fi
    
    # Also print to stdout
    echo "${ENV_VAR_NAME}=${TAG}"
done

echo -e "\nSuccessfully generated $OUTPUT_ENV"
